function serviceLine(amount: number, period: string): FeeLine[] {
  return [{ 费目: '服务费', 说明: `${period} 入廊管线日常运维服务费`, 金额: amount }]
}

function bill(
  id: number,
  no: string,
  contract: ServiceContract,
  period: string,
  version: number,
  lines: FeeLine[],
  status: Bill['状态'],
  extra: Partial<Bill> = {},
): Bill {
  return {
    id,
    结算单号: no,
    合同编号: contract.合同编号,
    权属单位: contract.权属单位,
    计费周期: period,
    版次: version,
    状态: status,
    明细: lines,
    对方确认金额: 0,
    已收金额: 0,
    生成时间: '2026-07-05 09:00',
    ...extra,
  }
}

function c(no: string): ServiceContract {
  const found = CONTRACTS.find((item) => item.合同编号 === no)
  if (!found) throw new Error(`种子合同缺失：${no}`)
  return found
}

