function buildBatchAndRows(bills: Bill[]): { batches: ImportBatch[]; rows: ReconcileRow[] } {
  const batch: ImportBatch = {
    id: 1,
    文件名: '权属单位2026Q2对账回函汇总.csv',
    导入时间: '2026-07-12 10:20',
    计费周期: '2026-Q2',
    操作人: '收费结算班组·李会计',
  }
  const rows: ReconcileRow[] = []
  let line = 2 // CSV 首行表头，数据从第 2 行起
  let rid = 1
  bills
    .filter((b) => b.计费周期 === '2026-Q2' && b.状态 !== '已作废')
    .sort((a, b) => a.id - b.id)
    .forEach((b) => {
      const receivable = b.明细.reduce((s, l) => s + l.金额, 0)
      const short = b.已收金额 < receivable
      rows.push({
        id: rid++,
        批次: 1,
        文件行号: line++,
        合同编号: b.合同编号,
        计费周期: b.计费周期,
        费目: '服务费',
        账列金额: receivable,
        回函确认金额: b.对方确认金额,
        回函已缴金额: b.已收金额,
        对方备注: short ? '资金计划延迟，余款下月补缴' : '核对无误',
        是否匹配: true,
        原因: '',
        结算单: b.id,
        核对结论: short ? `已匹配；少缴 ${receivable - b.已收金额} 元，结算单挂欠费并牵动管线复核` : '已匹配；账实相符，结算单结清',
      })
    })
  // 匹配不上的行：单独列出并说明原因，不影响其他行入账。
  rows.push({
    id: rid++,
    批次: 1,
    文件行号: 10,
    合同编号: 'HT-RL-2099-99',
    计费周期: '2026-Q2',
    费目: '服务费',
    账列金额: 0,
    回函确认金额: 5000,
    回函已缴金额: 5000,
    对方备注: '合作单位代回函',
    是否匹配: false,
    原因: '合同编号 HT-RL-2099-99 在入廊服务合同台账中不存在，无法按「合同编号+计费周期」匹配',
    核对结论: '未入账；退回对方核实合同编号',
  })
  rows.push({
    id: rid++,
    批次: 1,
    文件行号: 11,
    合同编号: 'HT-RL-2026-003',
    计费周期: '2026-Q2',
    费目: '服务费',
    账列金额: 0,
    回函确认金额: 15000,
    回函已缴金额: 0,
    对方备注: '预缴季度服务费',
    是否匹配: false,
    原因: '合同 HT-RL-2026-003 签订日期为 2026-07-01，2026-Q2 无有效结算单（首费周期为 2026-Q3）',
    核对结论: '未入账；挂「待核销来款」，冲抵后续周期结算单',
  })
  return { batches: [batch], rows }
}

