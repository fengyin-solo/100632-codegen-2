export function buildInitialFeeState(): FeeState {
  const contracts = CONTRACTS.map((item) => ({ ...item, 管线编号列表: [...item.管线编号列表] }))
  const bills = buildBills()
  const { batches, rows } = buildBatchAndRows(bills)
  return {
    contracts,
    bills,
    batches,
    reconRows: rows,
    reviews: buildReviews(),
    ledger: buildLedger(),
    seq: { bill: 18, batch: 1, recon: rows.length, review: 2, ledger: 4 },
  }
}
